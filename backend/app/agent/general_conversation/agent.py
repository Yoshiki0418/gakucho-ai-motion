def _agent_for_preaccepted_motion(agent: Agent, explicit_prompt: str | None) -> Agent:
    """Keep a queued user action from becoming another model tool call."""
    if explicit_prompt is None:
        return agent
    turn_instructions = f"""
            # このターン限定の優先指示
            ユーザーの身体動作はシステムが既に受理しています。
            生成は開始済み、または発話音声の完成待ちです。
            受理した動作（ユーザー指定の動作データ）: {explicit_prompt!r}
            generate_motion を呼ばず、行動タグも追加しないでください。
            関数呼び出し、ツールの引数、内部チャンネルや制御記号を会話本文に書かないでください。
            自然な会話の返答だけを出してください。
            動作と一緒に質問された内容には通常通り答えてください。
            必要な天気・時刻のツールや専門エージェントへの handoff は引き続き利用できます。
            """
    return agent.clone(
        instructions=(agent.instructions or "") + turn_instructions,
        tools=[tool for tool in agent.tools if getattr(tool, "name", None) != "generate_motion"],
    )


